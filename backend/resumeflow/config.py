"""Process-level configuration, supplied by the Tauri shell through environment variables.

Operator-editable preferences (output root, models, budgets, ...) live in the
``settings`` table instead; see ``resumeflow.services.settings``.
"""

from __future__ import annotations

import os
import secrets
from pathlib import Path
from typing import Literal

from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

LOOPBACK_HOSTS = {"127.0.0.1", "::1", "localhost"}


def default_data_dir() -> Path:
    base = os.environ.get("LOCALAPPDATA") or str(Path.home())
    return Path(base) / "ResumeFlowAI"


def default_output_root() -> Path:
    return Path.home() / "Documents" / "ResumeFlow AI" / "Applications"


class AppConfig(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="RESUMEFLOW_", extra="ignore")

    data_dir: Path = Field(default_factory=default_data_dir)
    host: str = "127.0.0.1"
    port: int = 8765
    # Per-session bearer token generated by the desktop shell. When absent an
    # unguessable ephemeral token is used, so the API is never left open.
    session_token: str = Field(default_factory=lambda: secrets.token_urlsafe(32))
    allowed_origins: list[str] = [
        "http://tauri.localhost",
        "https://tauri.localhost",
        "tauri://localhost",
    ]
    log_level: str = "INFO"
    # Background queue workers. Tests disable them and drain the queue explicitly.
    workers_enabled: bool = True
    # Daily automatic database backup on startup.
    auto_backup: bool = True
    # "memory" keeps API keys in this process only. The release smoke test uses it so it can never read
    # (or spend with) the operator's key from Windows Credential Manager.
    secret_backend: Literal["keyring", "memory"] = "keyring"

    @field_validator("host")
    @classmethod
    def _loopback_only(cls, value: str) -> str:
        if value not in LOOPBACK_HOSTS:
            raise ValueError("The sidecar may only bind to a loopback address")
        return value

    @field_validator("session_token")
    @classmethod
    def _strong_token(cls, value: str) -> str:
        if len(value) < 32:
            raise ValueError("Session token must be at least 32 characters")
        return value

    @property
    def database_path(self) -> Path:
        return self.data_dir / "resumeflow.db"

    @property
    def originals_dir(self) -> Path:
        return self.data_dir / "originals"

    @property
    def backups_dir(self) -> Path:
        return self.data_dir / "backups"

    @property
    def logs_dir(self) -> Path:
        return self.data_dir / "logs"

    def ensure_directories(self) -> None:
        for path in (self.data_dir, self.originals_dir, self.backups_dir, self.logs_dir):
            path.mkdir(parents=True, exist_ok=True)
